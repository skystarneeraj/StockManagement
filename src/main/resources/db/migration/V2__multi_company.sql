-- Converts the single-company schema to companies and branches.
-- Flyway runs this file in one transaction: if any statement fails, nothing is changed.
-- Existing data ends up in one company (from Company Settings) with one "Head Office" branch.

-- Columns added late in the single-company version, in case this database predates them.
alter table company_settings add column if not exists logo bytea;
alter table company_settings add column if not exists logo_type varchar(20);

-- 1. New tables ----------------------------------------------------------------------------------

create table companies (
    id                   bigint generated by default as identity primary key,
    name                 varchar(150) not null,
    code                 varchar(10)  not null unique,
    address              varchar(255),
    phone                varchar(20),
    email                varchar(100),
    gstin                varchar(15),
    state                varchar(50),
    logo                 bytea,
    logo_type            varchar(20),
    allow_negative_stock boolean      not null default false,
    active               boolean      not null default true,
    created_at           timestamp(6) not null default now()
);

create table branches (
    id          bigint generated by default as identity primary key,
    company_id  bigint       not null references companies,
    name        varchar(100) not null,
    code        varchar(10)  not null,
    address     varchar(255),
    phone       varchar(20),
    email       varchar(100),
    gstin       varchar(15),
    state       varchar(50),
    head_office boolean      not null default false,
    active      boolean      not null default true,
    constraint uk_branches_company_code unique (company_id, code)
);

create table user_branch (
    user_id   bigint not null references app_users on delete cascade,
    branch_id bigint not null references branches,
    primary key (user_id, branch_id)
);

create table branch_stock (
    id         bigint generated by default as identity primary key,
    branch_id  bigint  not null references branches,
    product_id bigint  not null references products,
    quantity   integer not null default 0,
    constraint uk_branch_stock unique (branch_id, product_id)
);

-- Last number issued per branch, document type and financial year (e.g. 2026-27).
create table doc_sequences (
    branch_id   bigint      not null references branches,
    doc_type    varchar(10) not null,
    fiscal_year varchar(7)  not null,
    last_number integer     not null,
    primary key (branch_id, doc_type, fiscal_year)
);

create table stock_transfers (
    id              bigint generated by default as identity primary key,
    company_id      bigint      not null references companies,
    transfer_number varchar(40) not null,
    from_branch_id  bigint      not null references branches,
    to_branch_id    bigint      not null references branches,
    date            date        not null,
    status          varchar(20) not null check (status in ('DRAFT', 'IN_TRANSIT', 'RECEIVED')),
    notes           varchar(255),
    created_by      varchar(50),
    received_by     varchar(50),
    received_date   date,
    constraint uk_stock_transfers_number unique (company_id, transfer_number),
    constraint ck_stock_transfers_branches check (from_branch_id <> to_branch_id)
);

create table stock_transfer_items (
    id          bigint generated by default as identity primary key,
    transfer_id bigint  not null references stock_transfers on delete cascade,
    product_id  bigint  not null references products,
    quantity    integer not null check (quantity > 0)
);

-- 2. Default company and Head Office branch from the existing data -------------------------------

insert into companies (name, code, address, phone, email, gstin, state, logo, logo_type)
select name,
       coalesce(nullif(left(regexp_replace(initcap(name), '[^A-Z0-9]', '', 'g'), 10), ''), 'CO'),
       address, phone, email, gstin, state, logo, logo_type
from company_settings
order by id
limit 1;

-- A database with data but no settings row still gets a company to own that data.
insert into companies (name, code)
select 'My Company', 'MC'
where not exists (select 1 from companies)
  and (exists (select 1 from app_users) or exists (select 1 from products)
    or exists (select 1 from customers) or exists (select 1 from suppliers));

insert into branches (company_id, name, code, address, phone, email, state, head_office)
select id, 'Head Office', 'HO', address, phone, email, state, true
from companies;

-- 3. Drop the old global unique constraints (their names are generated, so look them up) -------

do $$
declare
    r record;
begin
    for r in
        select c.conrelid::regclass as tbl, c.conname
        from pg_constraint c
        join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
        where c.contype = 'u' and cardinality(c.conkey) = 1
          and ((c.conrelid = 'categories'::regclass and a.attname = 'name')
            or (c.conrelid = 'uoms'::regclass and a.attname = 'name')
            or (c.conrelid = 'products'::regclass and a.attname = 'code')
            or (c.conrelid = 'sales'::regclass and a.attname = 'bill_number')
            or (c.conrelid = 'purchases'::regclass and a.attname = 'bill_number'))
    loop
        execute format('alter table %s drop constraint %I', r.tbl, r.conname);
    end loop;

    -- The role check only allows ADMIN and STAFF; it is replaced below.
    for r in
        select conname from pg_constraint
        where conrelid = 'app_users'::regclass and contype = 'c' and pg_get_constraintdef(oid) like '%role%'
    loop
        execute format('alter table app_users drop constraint %I', r.conname);
    end loop;
end $$;

-- 4. Assign every existing record to the default company / Head Office ---------------------------

alter table categories add column company_id bigint references companies;
alter table uoms       add column company_id bigint references companies;
alter table customers  add column company_id bigint references companies;
alter table suppliers  add column company_id bigint references companies;
alter table products   add column company_id bigint references companies;

update categories set company_id = (select min(id) from companies);
update uoms       set company_id = (select min(id) from companies);
update customers  set company_id = (select min(id) from companies);
update suppliers  set company_id = (select min(id) from companies);
update products   set company_id = (select min(id) from companies);

alter table categories alter column company_id set not null;
alter table uoms       alter column company_id set not null;
alter table customers  alter column company_id set not null;
alter table suppliers  alter column company_id set not null;
alter table products   alter column company_id set not null;

alter table sales     add column company_id bigint references companies, add column branch_id bigint references branches;
alter table purchases add column company_id bigint references companies, add column branch_id bigint references branches;
alter table payments  add column company_id bigint references companies, add column branch_id bigint references branches;

update sales     set company_id = (select min(id) from companies), branch_id = (select min(id) from branches);
update purchases set company_id = (select min(id) from companies), branch_id = (select min(id) from branches);
update payments  set company_id = (select min(id) from companies), branch_id = (select min(id) from branches);

alter table sales     alter column company_id set not null, alter column branch_id set not null;
alter table purchases alter column company_id set not null, alter column branch_id set not null;
alter table payments  alter column company_id set not null, alter column branch_id set not null;

-- Branch-wise numbers like KT-DEL-2026-27/0001 need more room; old numbers are kept as they are.
alter table sales     alter column bill_number type varchar(40);
alter table purchases alter column bill_number type varchar(40);

-- 5. Company-scoped unique constraints -----------------------------------------------------------

alter table categories add constraint uk_categories_company_name unique (company_id, name);
alter table uoms       add constraint uk_uoms_company_name unique (company_id, name);
alter table products   add constraint uk_products_company_code unique (company_id, code);
alter table sales      add constraint uk_sales_branch_bill unique (branch_id, bill_number);
alter table purchases  add constraint uk_purchases_branch_bill unique (branch_id, bill_number);

-- 6. Current stock becomes Head Office stock ----------------------------------------------------
-- products.quantity is kept (renamed) as a safety copy; a later migration drops it.

insert into branch_stock (branch_id, product_id, quantity)
select b.id, p.id, p.quantity
from products p
join branches b on b.company_id = p.company_id and b.head_office;

alter table products rename column quantity to legacy_quantity;
alter table products alter column legacy_quantity set default 0;

-- 7. Users: company, roles and branch access ----------------------------------------------------

alter table app_users add column company_id bigint references companies;
alter table app_users alter column role type varchar(20);
update app_users set company_id = (select min(id) from companies);
update app_users set role = 'COMPANY_ADMIN' where role = 'ADMIN';
alter table app_users add constraint ck_app_users_role
    check (role in ('SUPER_ADMIN', 'COMPANY_ADMIN', 'BRANCH_MANAGER', 'STAFF'));

insert into user_branch (user_id, branch_id)
select u.id, b.id
from app_users u
join branches b on b.company_id = u.company_id and b.head_office;

-- 8. Indexes for the per-company / per-branch lookups --------------------------------------------

create index ix_categories_company on categories (company_id);
create index ix_uoms_company       on uoms (company_id);
create index ix_customers_company  on customers (company_id);
create index ix_suppliers_company  on suppliers (company_id);
create index ix_sales_branch_date     on sales (branch_id, date);
create index ix_purchases_branch_date on purchases (branch_id, date);
create index ix_payments_branch_date  on payments (branch_id, date);
create index ix_branch_stock_product  on branch_stock (product_id);
create index ix_app_users_company     on app_users (company_id);
